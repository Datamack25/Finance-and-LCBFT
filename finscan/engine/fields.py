"""Dictionnaire des postes : libellés reconnus par format d'états financiers.

Chaque poste a une clé canonique (utilisée par les ratios), un libellé
français pour l'affichage, les libellés source acceptés (normalisés :
minuscules, sans accents) et les sections où on le cherche.

Sections : A = actif, P = passif, R = compte de résultat, F = flux de
trésorerie, X = annexe / notes. Pour les comptes US, les sous-sections
du bilan (CA, NCA, CL, NCL) affinent les postes en double.
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class FieldSpec:
    key: str
    labels: tuple[str, ...]
    sections: tuple[str, ...] = ("A", "P", "R")
    agg: str = "first"  # "first" ou "sum" (plusieurs lignes à additionner)
    charge: bool = False  # True : on garde la valeur absolue (charges présentées en négatif)
    sub: tuple[str, ...] = ()  # sous-sections autorisées (bilan US)
    occurrence: int = 1  # n-ième ligne correspondante (ex. 2e « Diluted »)


